const TABLES: Partial<Record<Locale, Table>> = { en: EN, de: DE, es: ES };

/** Message Postgres traduit (valeurs « % » reprises dans l'ordre), ou null si inconnu. */
export function translateSqlMessage(message: string, locale: Locale): string | null {
  if (locale === "fr") return message;
  const table = TABLES[locale];
  if (!table) return null;
  if (table[message]) return table[message];
  for (const [fr, tr] of Object.entries(table)) {
    if (!fr.includes("%")) continue;
    const pattern = new RegExp(`^${fr.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/%/g, "(.+?)")}$`);
    const match = message.match(pattern);
    if (!match) continue;
    let i = 1;
    return tr.replace(/%/g, () => match[i++] ?? "");
  }
  return null;
}
